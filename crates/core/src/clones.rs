//! Playlist copies made by iTunes syncs.
//!
//! When a playlist is edited on an iPhone or iPod touch, the device stores the
//! edit as a new playlist with the same name, and the next iTunes sync imports
//! it as "Name 1" next to the untouched "Name". This module finds those pairs
//! and writes an AppleScript that merges each copy back into its original.

use crate::{Library, Playlist};

/// A playlist and the copy iTunes made of it.
#[derive(Debug)]
pub struct ClonePair<'a> {
    pub original: &'a Playlist,
    pub copy: &'a Playlist,
    /// Tracks in the copy but not the original, in the copy's order.
    pub added: Vec<u64>,
    /// Tracks in the original but not the copy. Merging keeps them: it's
    /// unknown whether they were removed on the device or added in iTunes.
    pub missing: Vec<u64>,
}

/// Finds "Name N" playlists that copy a "Name" playlist. Only regular
/// playlists are considered, and a copy whose name matches more than one
/// regular playlist is skipped as ambiguous.
pub fn find(lib: &Library) -> Vec<ClonePair<'_>> {
    let regular = || lib.playlists.iter().filter(|p| !p.is_smart && !p.is_master);
    regular()
        .filter_map(|copy| {
            let base = copy_base_name(&copy.name)?;
            let mut originals = regular().filter(|p| p.name == base);
            let original = originals.next()?;
            if originals.next().is_some() {
                return None;
            }
            Some(ClonePair {
                original,
                copy,
                added: difference(&copy.track_ids, &original.track_ids),
                missing: difference(&original.track_ids, &copy.track_ids),
            })
        })
        .collect()
}

/// "Name 12" -> "Name".
fn copy_base_name(name: &str) -> Option<&str> {
    let (base, n) = name.rsplit_once(' ')?;
    let valid = !base.is_empty() && !n.starts_with('0') && n.bytes().all(|b| b.is_ascii_digit());
    (valid && !n.is_empty()).then_some(base)
}

fn difference(a: &[u64], b: &[u64]) -> Vec<u64> {
    let b: std::collections::HashSet<_> = b.iter().collect();
    a.iter().filter(|id| !b.contains(id)).copied().collect()
}

/// Writes an AppleScript for iTunes that appends each copy's added tracks to
/// its original and then deletes the copy. A copy is only deleted if its
/// original afterwards has the expected number of tracks; any failure is
/// reported in a dialog at the end. Pairs lacking persistent IDs are skipped.
pub fn merge_script(pairs: &[ClonePair]) -> String {
    let mut s = String::from(
        "-- Generated by betterTunes (bt clones --script).\n\
         -- Merges playlist copies made by iPhone/iPod sync back into the originals.\n\
         -- Run on the Mac with the iTunes library, while iTunes isn't syncing.\n\n\
         set failures to {}\n\
         tell application \"iTunes\"\n",
    );
    for p in pairs {
        let (Some(original), Some(copy)) = (p.original.persistent_id, p.copy.persistent_id) else {
            continue;
        };
        let label = quote(&format!("{} <- {}", p.original.name, p.copy.name));
        s += &format!(
            "\t-- {}: add {} tracks, then delete the copy\n\
             \ttry\n\
             \t\tset original to (first user playlist whose persistent ID is \"{original:016X}\")\n\
             \t\tset theCopy to (first user playlist whose persistent ID is \"{copy:016X}\")\n\
             \t\tset expected to (count tracks of original) + {}\n",
            p.original.name.replace('\n', " "),
            p.added.len(),
            p.added.len(),
        );
        for id in &p.added {
            s += &format!(
                "\t\tduplicate (first track of library playlist 1 whose persistent ID is \"{id:016X}\") to original\n"
            );
        }
        s += &format!(
            "\t\tif (count tracks of original) = expected then\n\
             \t\t\tdelete theCopy\n\
             \t\telse\n\
             \t\t\tset end of failures to {label} & \": track count mismatch, copy kept\"\n\
             \t\tend if\n\
             \ton error errMsg\n\
             \t\tset end of failures to {label} & \": \" & errMsg\n\
             \tend try\n\n"
        );
    }
    s += "end tell\n\n\
          if failures is {} then\n\
          \tdisplay dialog \"All playlist copies merged.\" buttons {\"OK\"} default button 1\n\
          else\n\
          \tset AppleScript's text item delimiters to return\n\
          \tdisplay dialog \"Some copies were not merged:\" & return & return & (failures as text) buttons {\"OK\"} default button 1\n\
          end if\n";
    s
}

/// An AppleScript string literal.
fn quote(s: &str) -> String {
    format!(
        "\"{}\"",
        s.replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('\n', " ")
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn playlist(id: u64, name: &str, tracks: &[u64]) -> Playlist {
        Playlist {
            persistent_id: Some(id),
            name: name.into(),
            track_ids: tracks.to_vec(),
            ..Default::default()
        }
    }

    #[test]
    fn parses_copy_names() {
        assert_eq!(copy_base_name("Favourites 1"), Some("Favourites"));
        assert_eq!(copy_base_name("new import 12"), Some("new import"));
        assert_eq!(copy_base_name("Top 100"), Some("Top"));
        for name in ["party", "mix 01", "mix 1a", " 1", "mix "] {
            assert_eq!(copy_base_name(name), None, "{name:?}");
        }
    }

    #[test]
    fn finds_copies() {
        let mut smart = playlist(5, "mix 1", &[1]);
        smart.is_smart = true;
        let lib = Library {
            tracks: vec![],
            playlists: vec![
                playlist(1, "Favourites", &[10, 11, 12]),
                playlist(2, "Favourites 1", &[10, 12, 13, 14]),
                playlist(3, "mix", &[1]),
                smart,
                playlist(6, "dup", &[]),
                playlist(7, "dup", &[]),
                playlist(8, "dup 1", &[]),
                playlist(9, "orphan 1", &[]),
            ],
        };
        let pairs = find(&lib);
        assert_eq!(pairs.len(), 1, "{pairs:?}");
        assert_eq!(pairs[0].original.name, "Favourites");
        assert_eq!(pairs[0].copy.name, "Favourites 1");
        assert_eq!(pairs[0].added, vec![13, 14]);
        assert_eq!(pairs[0].missing, vec![11]);
    }

    #[test]
    fn writes_merge_script() {
        let original = playlist(0x1111_2222_3333_4444, "say \"hi\"", &[1]);
        let copy = playlist(
            0x5555_6666_7777_8888,
            "say \"hi\" 1",
            &[1, 0xAAAA_BBBB_CCCC_0001],
        );
        let pair = ClonePair {
            original: &original,
            copy: &copy,
            added: vec![0xAAAA_BBBB_CCCC_0001],
            missing: vec![],
        };
        let script = merge_script(&[pair]);
        assert!(script.contains("persistent ID is \"1111222233334444\""));
        assert!(script.contains("persistent ID is \"5555666677778888\""));
        assert!(script.contains(
            "duplicate (first track of library playlist 1 whose persistent ID is \"AAAABBBBCCCC0001\") to original"
        ));
        assert!(script.contains("+ 1\n"));
        assert!(script.contains("\"say \\\"hi\\\" <- say \\\"hi\\\" 1\""));
        assert_eq!(script.matches("delete theCopy").count(), 1);
    }
}
